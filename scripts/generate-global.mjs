import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const srcDir = fileURLToPath(new URL("../src", import.meta.url));
const outFile = join(srcDir, "global.d.ts");

const skipFiles = new Set(["global.d.ts", "index.ts"]);

async function collectTsFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectTsFiles(fullPath)));
      continue;
    }

    if (entry.isFile() && entry.name.endsWith(".ts") && !skipFiles.has(entry.name)) {
      files.push(fullPath);
    }
  }

  return files.sort();
}

function parseExports(source) {
  const types = [];
  const values = [];

  for (const match of source.matchAll(/^export type (\w+)/gm)) {
    types.push(match[1]);
  }

  for (const match of source.matchAll(/^export const (\w+)/gm)) {
    values.push(match[1]);
  }

  return { types, values };
}

const files = await collectTsFiles(srcDir);
const imports = [];
const globalTypes = [];
const globalValues = [];

for (const [index, file] of files.entries()) {
  const source = await readFile(file, "utf8");
  const { types, values } = parseExports(source);

  if (types.length === 0 && values.length === 0) {
    continue;
  }

  const alias = `M${index}`;
  const importPath = `./${relative(srcDir, file).replace(/\.ts$/, ".js")}`;
  imports.push(`import * as ${alias} from "${importPath}";`);

  for (const name of types) {
    globalTypes.push(`  type ${name} = ${alias}.${name};`);
  }

  for (const name of values) {
    globalValues.push(`  const ${name}: typeof ${alias}.${name};`);
  }
}

const output = `/**
 * Ambient global declarations for all @types/tiqr exports.
 *
 * Enable once in your app — see README "Global types (no imports)".
 *
 * @generated by scripts/generate-global.mjs — do not edit manually
 */

${imports.join("\n")}

declare global {
${[...globalTypes, ...globalValues].join("\n")}
}

export {};
`;

await writeFile(outFile, output);
console.log(`Wrote ${outFile} (${globalTypes.length} types, ${globalValues.length} values)`);
